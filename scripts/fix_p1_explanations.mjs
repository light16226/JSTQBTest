function escapeReg(s) {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

// 旧解説から特定の行を取り出す
function getLine(expl, label) {
  const m = expl.match(new RegExp('^' + label + ': (.+)$', 'm'));
  return m ? m[1] : null;
}

