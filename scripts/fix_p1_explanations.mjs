// 誤答選択肢の内容分類(主な誤答の説明文を選択肢の内容に合わせる)
// ---------------------------------------------------------------
function classifyDistractor(text) {
  if (/同じ意味|同義/.test(text)) {
    return '異なる概念を同一視しており、用語の区別ができていない。';
  }
  if (/(すべて|全て|完全|必ず|常に|100%)[^。]{0,20}(保証|防げる|なくせる|なくなる|検出できる|見つけられる|網羅|示せる|証明|列挙|解決)/.test(text)) {
    return '完全性を保証できるという前提に寄っており、テストの限界を無視している。';
  }
  if (/不要|しなくてよい|なくてよい|省略|考えなくてよい|見直さな|そのまま(有効|動)|使い続けられる/.test(text)) {
    return '必要な活動や考慮事項を省いており、品質や保守性の問題を招く。';
  }
  if (/記録せず|記録しない|残さず|残さない|示さない|報告しない|追跡できない|文書化しない/.test(text)) {
    return '追跡や説明責任に必要な情報を軽視している。';
  }
  if (/関係なく|一律|同じ深さ|同じ詳しさ|同じテスト量|均等|同じ順序|区別せず|考慮せず|無視し|見ずに|評価せず|優先順位を付けず/.test(text)) {
    return 'リスクや重要度に応じた調整をしておらず、限られた時間と労力を有効に使えない。';
  }
  if (/遅らせ|終盤まで|完了後まで|終わるまで|後回し|最後にまとめて|開発完了後/.test(text)) {
    return '確認を後ろ倒しにしており、早期フィードバックの機会を失う。';
  }
  if (/だけ|のみ|しか/.test(text)) {
    return '対象や目的を一部に限定しすぎており、他の重要な側面を見落としている。';
  }
  return null;
}

