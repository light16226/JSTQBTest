def distribute_targets():
    by_chapter = defaultdict(list)
    for spec in LO_SPECS:
        by_chapter[spec["chapter"]].append(spec)

    targets = {}
    for chapter, specs in by_chapter.items():
        total = CHAPTER_TARGETS[chapter]
        weights = []
        for spec in specs:
            weight = 1
            if spec["k"] == "K3":
                weight += 2
            if chapter in {"4章", "5章"}:
                weight += 1
            if spec["section"] in {"4.2.1", "4.2.2", "4.2.3", "4.2.4", "5.1.4", "5.1.5", "5.5.1"}:
                weight += 2
            weights.append(weight)
        base = [total * w // sum(weights) for w in weights]
        remainder = total - sum(base)
        order = sorted(range(len(specs)), key=lambda i: (-weights[i], specs[i]["section"]))
        for i in order[:remainder]:
            base[i] += 1
        for spec, count in zip(specs, base):
            targets[spec["lo"]] = count
    return targets


def rotate(values, start):
    return [values[(start + i) % len(values)] for i in range(len(values))]


