def remove_tell_phrases(text):
    text = clean(text)
    for old, new in TELL_REPLACEMENTS.items():
        text = text.replace(old, new)
    text = text.replace("。そのうえで", "し、")
    text = text.replace("そのうえで", "あわせて")
    return clean(text)


