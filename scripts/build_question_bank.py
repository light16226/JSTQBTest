def validate(data):
    errors = []
    questions = data.get("questions")
    if not isinstance(questions, list):
        return ["questions is not a list"]
    if data.get("meta", {}).get("questionCount") != len(questions):
        errors.append("meta.questionCount does not match questions length")
    ids = [q.get("id") for q in questions]
    if len(ids) != len(set(ids)):
        errors.append("duplicate ids found")
    allowed = set(CHAPTER_TARGETS)
    required = {"id", "chapter", "question", "options", "answer", "correctIndex", "explanation"}
    for q in questions:
        missing = required - set(q)
        if missing:
            errors.append(f"{q.get('id')}: missing {sorted(missing)}")
        if q.get("chapter") not in allowed:
            errors.append(f"{q.get('id')}: invalid chapter")
        options = q.get("options")
        if not isinstance(options, list) or len(options) != 4:
            errors.append(f"{q.get('id')}: options length is not 4")
            continue
        if len(options) != len(set(options)):
            errors.append(f"{q.get('id')}: duplicate options")
        if any(not str(o).strip() for o in options):
            errors.append(f"{q.get('id')}: blank option")
        if q.get("answer") not in options:
            errors.append(f"{q.get('id')}: answer not in options")
        ci = q.get("correctIndex")
        if not isinstance(ci, int) or ci < 0 or ci >= 4:
            errors.append(f"{q.get('id')}: invalid correctIndex")
        elif options[ci] != q.get("answer"):
            errors.append(f"{q.get('id')}: correctIndex mismatch")
        if not str(q.get("question", "")).strip():
            errors.append(f"{q.get('id')}: blank question")
        if not str(q.get("explanation", "")).strip():
            errors.append(f"{q.get('id')}: blank explanation")
    return errors


