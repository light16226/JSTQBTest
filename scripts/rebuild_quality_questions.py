def get_detail(section):
    if section in SECTION_DETAILS:
        return SECTION_DETAILS[section]
    return (
        f"{section}の学習項目",
        [f"{section}の目的、対象、制約を踏まえてテスト活動を選ぶ"],
        [f"{section}を他の活動と区別せず、目的や対象を確認しない"],
    )


def rotate(values, offset):
    return [values[(offset + i) % len(values)] for i in range(len(values))]


def clean_title(explanation, section):
    match = re.search(r"\[(.*?)\]", explanation or "")
    if match:
        return match.group(1)
    term, _, _ = get_detail(section)
    return f"{section} {term}"


def unique_options(options):
    seen = set()
    result = []
    for option in options:
        text = re.sub(r"\s+", " ", option).strip()
        if text and text not in seen:
            seen.add(text)
            result.append(text)
    return result


def strip_option_context(option):
    if "。" in option:
        return option.rsplit("。", 1)[-1].strip()
    return option.strip()


def balance_option_lengths(options, answer):
    if answer not in options:
        return options
    answer_len = len(answer)
    if answer_len < max(len(option) for option in options):
        return options
    balanced = list(options)
    for index, option in enumerate(balanced):
        if option != answer:
            suffixes = ["という説明を採用する", "という観点で判断する", "という前提で扱う"]
            suffix_index = 0
            candidate = option
            while len(candidate) <= answer_len:
                candidate = f"{candidate}{suffixes[suffix_index % len(suffixes)]}"
                suffix_index += 1
            balanced[index] = candidate
            break
    return balanced


def clean_calculation_question(q, ordinal):
    new_q = dict(q)
    section = q.get("section", "")
    heading = clean_title(q.get("explanation", ""), section)
    field = f"{CALC_FIELDS[(ordinal - 1) % len(CALC_FIELDS)]}{chr(65 + ((ordinal - 1) % 26))}"
    question = q.get("question", "")
    if "入力欄" in question:
        question = question.replace("入力欄", field, 1)
    question = f"{question.rstrip('。')}。対象は{field}とする。"

    cleaned_options = [strip_option_context(option) for option in q.get("options", [])]
    cleaned_answer = strip_option_context(q.get("answer", ""))
    if cleaned_answer not in cleaned_options:
        cleaned_options[q.get("correctIndex", 0)] = cleaned_answer

    # Remove accidental duplicate labels while preserving the intended answer.
    if len(set(cleaned_options)) != len(cleaned_options):
        seen = set()
        adjusted = []
        for option in cleaned_options:
            candidate = option
            suffix = 2
            while candidate in seen:
                candidate = f"{option}（別条件）" if suffix == 2 else f"{option}（別条件{suffix}）"
                suffix += 1
            seen.add(candidate)
            adjusted.append(candidate)
        cleaned_options = adjusted
        cleaned_answer = cleaned_options[q.get("correctIndex", 0)]
    cleaned_options = balance_option_lengths(cleaned_options, cleaned_answer)

    explanation_body = CALC_EXPLANATIONS.get(section, "計算問題では、条件と期待結果を対応付けて判断する。")
    new_q["question"] = question
    new_q["options"] = cleaned_options
    new_q["answer"] = cleaned_answer
    new_q["correctIndex"] = cleaned_options.index(cleaned_answer)
    new_q["explanation"] = (
        f"[{heading}]\n"
        f"正解は「{cleaned_answer}」。{explanation_body}"
        f"\n根拠: JSTQB Foundation Level シラバス Version 2023V4.0.J02 の {section} に基づくオリジナル問題。"
    )
    return new_q


def build_question(q, ordinal):
    section = q.get("section", "")
    term, points, pitfalls = get_detail(section)
    qtype = q.get("questionType", "scenario")
    focus = FOCUSES[(ordinal + len(section)) % len(FOCUSES)]
    scenario, scenario_action = SCENARIOS[(ordinal + int(section.split(".")[0])) % len(SCENARIOS)]

    if qtype == "calculation":
        return clean_calculation_question(q, ordinal), True

    point_pool = rotate(points, ordinal)
    pitfall_pool = rotate(pitfalls, ordinal * 2 + 1)

    if qtype == "negative":
        answer = pitfall_pool[0]
        distractors = point_pool[:3]
    elif qtype == "scenario":
        answer = f"{scenario_action}。そのうえで{point_pool[0]}"
        distractors = [f"{scenario_action}よりも、{d}" for d in pitfall_pool[:3]]
    elif qtype == "example":
        answer = f"{point_pool[0]}場面で、{scenario_action}"
        distractors = [f"{d}場面で、{scenario_action}" for d in pitfall_pool[:3]]
    elif qtype == "purpose":
        answer = point_pool[0]
        distractors = pitfall_pool[:3]
    elif qtype == "definition":
        answer = point_pool[0]
        distractors = pitfall_pool[:3]
    elif qtype == "distinction":
        answer = point_pool[0]
        distractors = pitfall_pool[:3]
    elif qtype == "process":
        answer = f"{point_pool[0]}ように、作業の順序と確認内容を決める"
        distractors = [f"{d}ように、作業の順序と確認内容を決める" for d in pitfall_pool[:3]]
    elif qtype == "misconception":
        answer = point_pool[0]
        distractors = pitfall_pool[:3]
    else:
        answer = point_pool[0]
        distractors = pitfall_pool[:3]

    options = unique_options([answer] + distractors)
    filler_index = 0
    while len(options) < 4:
        candidate = rotate(pitfalls + points, ordinal + filler_index)[0]
        if candidate not in options:
            options.append(candidate)
        filler_index += 1

    correct_index = (ordinal + sum(ord(c) for c in q.get("id", ""))) % 4
    options_without_answer = [o for o in options if o != answer][:3]
    final_options = options_without_answer[:]
    final_options.insert(correct_index, answer)
    final_options = balance_option_lengths(final_options, answer)

    if qtype == "scenario":
        question = TYPE_QUESTION[qtype].format(term=term, focus=focus, scenario=scenario)
    else:
        question = TYPE_QUESTION.get(qtype, TYPE_QUESTION["scenario"]).format(term=term, focus=focus, scenario=scenario)

    heading = clean_title(q.get("explanation", ""), section)
    if qtype == "negative":
        explanation = (
            f"[{heading}]\n"
            f"正解は「{answer}」。これは{term}の考え方と合わない説明である。"
            f"他の選択肢は、{term}の目的や適用条件に沿った説明である。"
            f"\n根拠: JSTQB Foundation Level シラバス Version 2023V4.0.J02 の {section} に基づくオリジナル問題。"
        )
    else:
        explanation = (
            f"[{heading}]\n"
            f"正解は「{answer}」。{term}では、{point_pool[0]}ことが重要である。"
            f"他の選択肢は、目的、対象、適用条件のいずれかを取り違えている。"
            f"\n根拠: JSTQB Foundation Level シラバス Version 2023V4.0.J02 の {section} に基づくオリジナル問題。"
        )

    new_q = dict(q)
    new_q["question"] = question
    new_q["options"] = final_options
    new_q["answer"] = answer
    new_q["correctIndex"] = correct_index
    new_q["explanation"] = explanation
    return new_q, True


def sync_data_js(data):
    embedded = json.dumps(data, ensure_ascii=False, separators=(",", ":"))
    DATA_JS_PATH.write_text(f"window.EMBEDDED_QUESTIONS = {embedded};\n", encoding="utf-8")


def main():
    data = json.loads(QUESTIONS_PATH.read_text(encoding="utf-8"))
    section_ordinals = defaultdict(int)
    updated = []
    modified = 0
    for question in data["questions"]:
        section = question.get("section", "")
        section_ordinals[section] += 1
        rebuilt, changed = build_question(question, section_ordinals[section])
        updated.append(rebuilt)
        if changed:
            modified += 1

    data["questions"] = updated
    data["meta"]["questionCount"] = len(updated)
    data["meta"]["createdAt"] = datetime.now().strftime("%Y-%m-%dT%H:%M:%S")

    QUESTIONS_PATH.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    sync_data_js(data)

    print("modified_questions", modified)
    print("question_count", len(updated))
    print("type_counts", dict(Counter(q.get("questionType", "") for q in updated)))


if __name__ == "__main__":
    main()
